"""Compile tools/trellis/reports/REPORT.md from the recorded pipeline data.

    python3 tools/trellis/report.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPORTS = os.path.join(HERE, 'reports')
CHARS = ['lifeline', 'vanguard', 'wraith', 'bathysphere']


def load(name, default=None):
    path = os.path.join(REPORTS, name)
    return json.load(open(path)) if os.path.exists(path) else default


def main():
    manifest = json.load(open(os.path.join(HERE, 'originals', 'manifest.json')))
    mapping = json.load(open(os.path.join(HERE, 'mapping.json')))
    ident = load('identification.json', {})
    config = json.load(open(os.path.join(HERE, 'characters.json')))
    rows = {r['source']: r for r in ident.get('assignments', [])}
    out = ['# TRELLIS character pipeline report', '',
           'Generated by `tools/trellis/report.py` from the pipeline\'s recorded data.', '',
           '## Sources', '', '| Source | Remote file | Bytes | SHA-256 | Character | Confidence |', '|---|---|---|---|---|---|']
    by_source = {v['source']: k for k, v in mapping.items()}
    for key, m in sorted(manifest.items()):
        r = rows.get(key, {})
        out.append('| %s | `%s` | %d | `%s…` | %s | %s |' % (key, m['remote_filename'], m['size'], m['sha256'][:16],
                                                       by_source.get(key, '?'), r.get('confidence', '?')))
    out += ['', 'Identification: assignment margin %s over the runner-up, mutually consistent: %s.' % (
        ident.get('assignment_margin'), ident.get('consistent')), '']
    for c in CHARS:
        src = mapping[c]['source']
        diag = load('source_%s_diagnostics.json' % src, {})
        master = load(c + '_master.json', {})
        runtime = load(c + '_runtime.json', {})
        check = load(c + '_export_check.json', {})
        r = rows.get(src, {})
        geo = master.get('geometry', {})
        out += ['## %s (source %s)' % (c.upper(), src), '',
                '- Source URL: %s' % mapping[c]['source_url'],
                '- Identification: %s confidence; signal distances %s; palette shares %s' % (
                    r.get('confidence'), r.get('signal_distances'), r.get('palette_share')),
                '- Original: %s vertices / %s triangles, %s mesh object, %s material, %s armature; textures %s' % (
                    diag.get('vertices'), diag.get('triangles'), diag.get('mesh_objects'), len(diag.get('materials', [])),
                    diag.get('armatures'), [t['size'] for m in diag.get('materials', []) for t in m['textures']]),
                '- Master refinement: welded %s seam-split vertices, removed %s floater vertices; after: %s' % (
                    geo.get('welded_seam_vertices'), geo.get('removed_floater_vertices'), geo.get('after')),
                '- Material classes (texel share): %s' % master.get('class_coverage'),
                '- Runtime: %s triangles (from %s), %s px albedo/ORM/normal, GLB %s bytes (%s before meshopt)' % (
                    runtime.get('runtime_triangles'), runtime.get('source_triangles'), runtime.get('texture_size'),
                    runtime.get('glb_bytes'), runtime.get('raw_glb_bytes')),
                '- Rig: rigid segments on the game\'s 15-joint teammate rig, suit-specific pivots %s' % (
                    {k: v for k, v in runtime.get('landmarks_m', {}).items() if k in ('hip', 'knee', 'neck', 'shoulder_x', 'arm_z')}),
                '- Export re-import check: %s (height %s m)' % ('OK' if check.get('ok') else check.get('problems'), check.get('height_m')),
                '- Known issues: %s' % '; '.join(config[c].get('known_issues', [])),
                '- Renders: `renders/%s/A_*.png` (original), `B_*.png` (enhanced), `QA_classes_*`, `QA_segments_*`' % c, '']
    path = os.path.join(REPORTS, 'REPORT.md')
    open(path, 'w').write('\n'.join(out) + '\n')
    print('Wrote', path)


if __name__ == '__main__':
    main()
